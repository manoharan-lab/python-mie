"""
Tests the pymie results against stored values from the reference
(arbitrary-precision) Mie implementation in mie_reference.py.  The reference
values are generated by generate_reference_values.py.

.. moduleauthor:: Vinothan N. Manoharan <vnm@seas.harvard.edu>
   (with assistance from Claude Opus 5.5)
"""
import ast
import json
from pathlib import Path

import numpy as np
from numpy.testing import assert_allclose
import pytest

from .. import mie, mie_specfuncs

# load reference values generated by arbitrary-precision (mpmath) Mie
# implementation
with open(Path(__file__).with_name("reference_values.json")) as f:
    REFERENCE_VALUES = json.load(f)


def to_array(strings):
    """Convert a list of stored strings to an array.  Uses ast.literal_eval()
    to handle real and complex inputs.  Real inputs stay real, so pymie sees
    the same input types that were used to generate the reference values.

    """
    return np.array([ast.literal_eval(s) for s in strings])


@pytest.mark.parametrize("values", REFERENCE_VALUES["riccati"],
                         ids=lambda values: (f"z={values['z']};"
                                             f"nstop={values['nstop']}"))
def test_riccati_psi_xi_matches_reference(values):
    """Tests that pymie Riccati-Bessel functions return results that match
    stored values from the reference (mpmath) implementation.

    """
    z = ast.literal_eval(values["z"])
    psi = to_array(values["psi"])
    xi = to_array(values["xi"])
    psi_pymie, xi_pymie = mie_specfuncs.riccati_psi_xi(z, values["nstop"])


    # In the oscillatory region (n <= |z|), psi_n is of order 1 but passes
    # through zeros, where relative errors are not meaningful (and depend on
    # platform-specific rounding), so we use an absolute tolerance there.  For
    # n > |z|, psi_n decays rapidly, and we require full relative accuracy,
    # which guards against unstable upward recurrence.
    n = np.arange(values["nstop"] + 1)
    oscillatory = n <= abs(z)
    assert_allclose(psi_pymie[oscillatory], psi[oscillatory], rtol=1e-12,
                    atol=1e-13)
    assert_allclose(psi_pymie[~oscillatory], psi[~oscillatory], rtol=1e-12)
    assert_allclose(xi_pymie, xi, rtol=1e-12)


def particle_id(particle):
    """Generate an ID (for output by pytest) showing the layer values of m and
    x for the current test. Example: "m=1.5;x=10.0"

    """
    return f"m={','.join(particle['m'])};x={','.join(particle['x'])}"


@pytest.mark.parametrize("particle", REFERENCE_VALUES["particles"],
                         ids=particle_id)
def test_scatcoeffs_match_reference(particle):
    """Tests that pymie's scattering coefficients match the stored values of
    the reference (mpmath) implementation.

    """
    m = to_array(particle["m"])
    x = to_array(particle["x"])
    a = to_array(particle["a"])
    b = to_array(particle["b"])
    a_pymie, b_pymie = mie._scatcoeffs(m, x, particle["nstop"])[:, 0]
    assert_allclose(a_pymie, a, rtol=1e-10, atol=1e-13)
    assert_allclose(b_pymie, b, rtol=1e-10, atol=1e-13)


@pytest.mark.parametrize("particle", REFERENCE_VALUES["particles"],
                         ids=particle_id)
def test_efficiencies_match_reference(particle):
    """Tests that pymie's scattering efficiencies (including asymmetry
    parameter) match the stored values from the mpmath reference
    implementation.

    """
    m = to_array(particle["m"])
    x = to_array(particle["x"])
    qsca_pymie, qext_pymie, qback_pymie = mie.calc_efficiencies(m, x)
    g_pymie = mie.calc_g(m, x)
    assert_allclose(qsca_pymie, float(particle["qsca"]), rtol=1e-12)
    assert_allclose(qext_pymie, float(particle["qext"]), rtol=1e-12)
    assert_allclose(qback_pymie, float(particle["qback"]), rtol=1e-12)
    # looser tolerance for g because pymie calculates b_1 with a larger
    # relative error than a_1 using B&H 4.88 (perhaps because of cancellation
    # in the numerator at small x)
    assert_allclose(g_pymie, float(particle["g"]), rtol=1e-10)


@pytest.mark.parametrize("values", REFERENCE_VALUES["angular"],
                         ids=lambda values: f"theta={values['theta']}")
def test_pis_and_taus_match_reference(values):
    """Tests that pymie's angular functions pi_n and tau_n match the stored
    values calculated from the reference implementation.

    """
    theta = ast.literal_eval(values["theta"])
    nstop = values["nstop"]
    pi = to_array(values["pi"])
    tau = to_array(values["tau"])
    pi_pymie, tau_pymie = mie._pis_and_taus(nstop, theta)
    # In the forward direction (mu=1), pi_n and tau_n are n(n+1)/2 (see B&H
    # page 112).  We normalize by this value so that all orders are on the same
    # scale, making it possible to test all orders using a single absolute
    # tolerance.  We disable relative tolerance checking in case theta is
    # near a zero of one of the angular functions.
    n = np.arange(1, nstop + 1)
    bound = n*(n + 1)/2
    # shape of pi_pymie and tau_pymie is (1, nstop), so we squeeze first
    assert_allclose(pi_pymie.squeeze()/bound, pi/bound, rtol=0, atol=1e-12)
    assert_allclose(tau_pymie.squeeze()/bound, tau/bound, rtol=0, atol=1e-12)


@pytest.mark.parametrize("particle", REFERENCE_VALUES["particles"],
                         ids=particle_id)
def test_amplitude_scattering_matrix_matches_reference(particle):
    """Tests that pymie's scattering amplitude matrix elements S_1 and S_2
    match the stored values from the mpmath reference implementation.

    """
    m = to_array(particle["m"])
    x = to_array(particle["x"])
    thetas = to_array(particle["thetas"])
    S1 = to_array(particle["S1"])
    S2 = to_array(particle["S2"])
    S_pymie = mie.amplitude_scattering_matrix(m, x, thetas)
    S1_pymie = S_pymie[0][0]
    S2_pymie = S_pymie[1][0]

    # because S can vary so much with angle, we scale the absolute tolerance by
    # the forward-scattering amplitude. We also use a relative tolerance.
    scale = np.abs(S1[0])
    assert_allclose(S1_pymie, S1, rtol=1e-12, atol=1e-13*scale)
    assert_allclose(S2_pymie, S2, rtol=1e-12, atol=1e-13*scale)
